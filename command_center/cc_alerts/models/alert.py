import uuid
from django.db import models
from django.utils import timezone
from django.core.validators import MinValueValidator, MaxValueValidator

from cc_alerts.models.alert_status import AlertStatus


# Create your models here.
class Alert(models.Model):
    """
    Model to store alerts generated by edge devices (e.g., YOLO detections).
    """
    SEVERITY_CHOICES = [
        ('low', 'Low'),
        ('medium', 'Medium'),
        ('high', 'High'),
        ('critical', 'Critical'),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=True)

    message = models.TextField(help_text="Detailed description of the alert.")
    
    inference_analysis = models.TextField(
        null=True,
        blank=True,
        help_text="Inference analysis results for the alert."
    )
    
    llm_response = models.TextField(
        null=True,
        blank=True,
        help_text="LLM response for the alert."
    )
    
    severity = models.CharField(
        max_length=10,
        choices=SEVERITY_CHOICES,
        default='medium',
        help_text="Urgency/importance level of the alert."
    )
    
    detection_class = models.CharField(
        max_length=100,
        blank=True,
        null=True,
        help_text="The object class detected that triggered the alert (e.g., 'no-hard-hat')."
    )

    confidence = models.FloatField(
        null=True,
        blank=True,
        help_text="Confidence score of the detection (0.0 to 1.0)."
    )

    alert_analysis = models.CharField(
        max_length=20,
        choices=AlertStatus.choices,
        default=AlertStatus.ACTIVE,
        help_text="Status of the video processing for this alert.",
        null=True,
        blank=True
    )
    
    latitude = models.DecimalField(
        max_digits=10, 
        decimal_places=8,
        null=True,
        validators=[MinValueValidator(-90), MaxValueValidator(90)],
        help_text="Latitude in decimal degrees"
    )
    longitude = models.DecimalField(
        max_digits=11, 
        decimal_places=8,
        null=True,
        validators=[MinValueValidator(-180), MaxValueValidator(180)],
        help_text="Longitude in decimal degrees"
    )

    start_time = models.DateTimeField(default=timezone.now, help_text="When the alert was recorded.")
    
    end_time = models.DateTimeField(default=None, null=True, help_text="End time of that alert.")
    
    duration = models.FloatField(null=True, blank=True, help_text="Duration of the alert in seconds.")

    # Status fields for command center to manage alerts
    is_resolved = models.BooleanField(default=False, help_text="Whether the alert has been resolved by an operator.")
    resolved_at = models.DateTimeField(null=True, blank=True, help_text="When the alert was marked as resolved.")
    resolution_notes = models.TextField(blank=True, null=True, help_text="Notes on how the alert was resolved.")
    
    # Multi-camera support
    is_active = models.BooleanField(default=True, help_text="Whether the alert is currently active and being monitored.")

    class Meta:
        verbose_name = "Alert"
        verbose_name_plural = "Alerts"
        ordering = ['-start_time'] # Order by newest alerts first

    def __str__(self):
        # Convert any lazy translation objects to strings to prevent TypeError
        severity_display = str(self.get_severity_display())
        detection_class = str(self.detection_class) if self.detection_class else ""
        start_time_str = self.start_time.strftime('%Y-%m-%d %H:%M:%S')
        return f"[{severity_display}] {detection_class} from ({start_time_str})"
